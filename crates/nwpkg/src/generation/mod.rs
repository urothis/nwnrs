const EMPTY_EVENT_DISPATCHER: &str = "/// Generated by nwpkg. Do not edit.\nvoid main() {}\n";

fn empty_event_project_plan() -> EventProjectPlan {
    EventProjectPlan {
        complete: true,
        ..EventProjectPlan::default()
    }
}

struct EventRecoveryRequest<'a> {
    source_path: &'a Path,
    context:     &'a EventCompletionContext,
}

/// Resolves an event completion context and, for relationship targets, runs
/// the canonical project macro in editor-recovery mode.
///
/// The recovery overlay is private to this call. Strict compilation and
/// packaging never receive the recovery marker or synthesized target.
///
/// # Errors
///
/// Returns a source-aware diagnostic for package resolution, source loading,
/// macro validation outside the active incomplete target, or cancellation.
pub fn analyze_event_completion_with_overlays_and_cancellation(
    input: &Path,
    overlays: &BTreeMap<PathBuf, Vec<u8>>,
    source_path: &Path,
    cursor_offset: usize,
    cancellation: &CancellationToken,
) -> Result<Option<EventCompletionAnalysis>, Box<CompilerDiagnostic>> {
    let Some(session) = ResolvedPackageSession::open(input, overlays, cancellation)
        .map_err(boxed_plain_diagnostic)?
    else {
        return Ok(None);
    };
    analyze_event_completion_from_session_with_cancellation(
        &session,
        source_path,
        cursor_offset,
        cancellation,
    )
}

/// Analyzes one event-completion position against an already synchronized
/// package session.
///
/// This is the persistent-language-service entry point. It never reopens the
/// package and performs recovery only by editing the compiler token stream.
pub fn analyze_event_completion_from_session_with_cancellation(
    session: &ResolvedPackageSession,
    source_path: &Path,
    cursor_offset: usize,
    cancellation: &CancellationToken,
) -> Result<Option<EventCompletionAnalysis>, Box<CompilerDiagnostic>> {
    let source = session
        .read_source_with_cancellation(source_path, cancellation)
        .map_err(boxed_plain_diagnostic)?;
    let edit_source = SourceFile::new(
        SourceId::new(0),
        source_path.display().to_string(),
        source.clone(),
    );
    let lexed = lex_source_recovering_with_limits_and_cancellation(
        &edit_source,
        CompilerResourceLimits::default(),
        Some(cancellation),
    )
    .map_err(|error| {
        boxed_source_diagnostic(
            error.message.clone(),
            Some(error.code.code()),
            &edit_source,
            error.span,
        )
    })?;
    let Some(context) = event_completion_context(&source, cursor_offset, &lexed.tokens) else {
        return Ok(None);
    };
    if context.kind != EventCompletionKind::Target {
        return Ok(Some(EventCompletionAnalysis {
            context,
            candidates: Vec::new(),
            plan: None,
        }));
    }

    let generated = generate_event_dispatcher_from_session_mode(
        session,
        cancellation,
        Some(&EventRecoveryRequest {
            source_path,
            context: &context,
        }),
    )?
    .ok_or_else(|| boxed_plain_diagnostic("event completion requires a module package"))?;
    let candidates = list_event_lane_handlers(&generated.plan, &context);
    Ok(Some(EventCompletionAnalysis {
        context,
        candidates,
        plan: Some(generated.plan),
    }))
}

/// Returns the strict macro-produced event plan for the nearest module.
///
/// # Errors
///
/// Returns the same source-aware diagnostics as dispatcher generation.
pub fn analyze_event_project_with_overlays_and_cancellation(
    input: &Path,
    overlays: &BTreeMap<PathBuf, Vec<u8>>,
    cancellation: &CancellationToken,
) -> Result<Option<EventProjectPlan>, Box<CompilerDiagnostic>> {
    let Some(session) = ResolvedPackageSession::open(input, overlays, cancellation)
        .map_err(boxed_plain_diagnostic)?
    else {
        return Ok(None);
    };
    generate_event_dispatcher_from_session_with_cancellation(&session, cancellation)
        .map(|generated| generated.map(|generated| generated.plan))
}

/// Runs the nwnrs NSS project macro over the nearest module project and
/// produces the always-present `_nwnrs_onload` dispatcher.
///
/// # Errors
///
/// Returns an error when the project cannot be resolved, a source cannot be
/// read or lexed, or the NSS macro rejects an event registration.
pub fn generate_event_dispatcher(input: &Path) -> Result<Option<GeneratedEventDispatcher>, String> {
    generate_event_dispatcher_with_diagnostics(input).map_err(|diagnostic| diagnostic.message)
}

/// Runs the canonical event project macro while retaining structured source
/// diagnostics for editor and automation clients.
///
/// # Errors
///
/// Returns a source-aware diagnostic when project discovery, source loading,
/// macro compilation, validation, or expansion fails.
pub fn generate_event_dispatcher_with_diagnostics(
    input: &Path,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    generate_event_dispatcher_with_cancellation(input, &CancellationToken::new())
}

/// Runs the canonical event project macro with caller-owned cancellation.
///
/// # Errors
///
/// Returns the same diagnostics as
/// [`generate_event_dispatcher_with_diagnostics`], including cancellation.
pub fn generate_event_dispatcher_with_cancellation(
    input: &Path,
    cancellation: &CancellationToken,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    generate_event_dispatcher_with_overlays_and_cancellation(input, &BTreeMap::new(), cancellation)
}

/// Runs the canonical event project macro using unsaved source overlays.
///
/// # Errors
///
/// Returns the same source-aware diagnostics as
/// [`generate_event_dispatcher_with_diagnostics`].
pub fn generate_event_dispatcher_with_overlays(
    input: &Path,
    overlays: &BTreeMap<PathBuf, Vec<u8>>,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    let cancellation = CancellationToken::new();
    generate_event_dispatcher_with_overlays_and_cancellation(input, overlays, &cancellation)
}

/// Runs the canonical event project macro with unsaved source overlays and
/// caller-owned cancellation.
///
/// # Errors
///
/// Returns a source-aware diagnostic for resolution, source, macro, or
/// cancellation failures.
pub fn generate_event_dispatcher_with_overlays_and_cancellation(
    input: &Path,
    overlays: &BTreeMap<PathBuf, Vec<u8>>,
    cancellation: &CancellationToken,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    let Some(session) = ResolvedPackageSession::open(input, overlays, cancellation)
        .map_err(boxed_plain_diagnostic)?
    else {
        return Ok(None);
    };
    generate_event_dispatcher_from_session_with_cancellation(&session, cancellation)
}

/// Generates the event dispatcher from an already-resolved package snapshot.
///
/// This is the preferred entry point for pipelines that also need package
/// roots, overlays, or dependency information.
///
/// # Errors
///
/// Returns a source-aware diagnostic for source, macro, or cancellation
/// failures.
pub fn generate_event_dispatcher_from_session(
    session: &ResolvedPackageSession,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    generate_event_dispatcher_from_session_with_cancellation(session, &CancellationToken::new())
}

/// Generates the event dispatcher from a resolved snapshot with caller-owned
/// cancellation.
pub fn generate_event_dispatcher_from_session_with_cancellation(
    session: &ResolvedPackageSession,
    cancellation: &CancellationToken,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    generate_event_dispatcher_from_session_mode(session, cancellation, None)
}

fn generate_event_dispatcher_from_session_mode(
    session: &ResolvedPackageSession,
    cancellation: &CancellationToken,
    recovery: Option<&EventRecoveryRequest<'_>>,
) -> Result<Option<GeneratedEventDispatcher>, Box<CompilerDiagnostic>> {
    cancellation
        .check()
        .map_err(|error| boxed_plain_diagnostic(error.to_string()))?;
    if session.manifest().project.kind != crate::ProjectKind::Mod {
        return Ok(None);
    }
    let source_root = session.source_root().to_path_buf();

    let paths = session
        .nss_source_paths_with_cancellation(cancellation)
        .map_err(boxed_plain_diagnostic)?;
    let mut source_input = NwTokenStream::new();
    let mut source_files = BTreeMap::new();
    let mut invocation_span = None;
    let mut recovery_token = None;
    for (source_index, path) in paths.iter().enumerate() {
        cancellation
            .check()
            .map_err(|error| boxed_plain_diagnostic(error.to_string()))?;
        if path
            .file_stem()
            .and_then(OsStr::to_str)
            .is_some_and(|stem| {
                stem.eq_ignore_ascii_case("_nwnrs_onload") || stem.eq_ignore_ascii_case("nwscript")
            })
        {
            continue;
        }
        let bytes = session
            .read_source_with_cancellation(path, cancellation)
            .map_err(boxed_plain_diagnostic)?;
        let source_id = SourceId::new(u32::try_from(source_index).map_err(|_error| {
            boxed_plain_diagnostic(
                "module contains too many NWScript source files for event collection",
            )
        })?);
        let source = SourceFile::new(source_id, path.display().to_string(), bytes);
        let tokens = if recovery.is_some_and(|recovery| {
            nwnrs_nwscript::physical_sources_equal(path, recovery.source_path)
        }) {
            let lexed = lex_source_recovering_with_limits_and_cancellation(
                &source,
                CompilerResourceLimits::default(),
                Some(cancellation),
            )
            .map_err(|error| {
                boxed_source_diagnostic(
                    format!("failed to recoveringly lex {}: {error}", path.display()),
                    Some(error.code.code()),
                    &source,
                    error.span,
                )
            })?;
            if let Some(error) = lexed.diagnostics.first() {
                return Err(boxed_source_diagnostic(
                    format!("failed to lex {}: {error}", path.display()),
                    Some(error.code.code()),
                    &source,
                    error.span,
                ));
            }
            let request = recovery.ok_or_else(|| {
                boxed_plain_diagnostic("event recovery source matched without a recovery request")
            })?;
            let (tokens, injected) =
                recover_active_event_target_tokens(&lexed.tokens, request.context, source_id)
                    .ok_or_else(|| {
                        boxed_plain_diagnostic(
                            "failed to recover the active event relationship token stream",
                        )
                    })?;
            recovery_token = Some(injected);
            tokens
        } else {
            lex_source_with_limits_and_cancellation(
                &source,
                CompilerResourceLimits::default(),
                Some(cancellation),
            )
            .map_err(|error| {
                boxed_source_diagnostic(
                    format!("failed to lex {}: {error}", path.display()),
                    Some(error.code.code()),
                    &source,
                    error.span,
                )
            })?
        };
        let stream = NwTokenStream::from_tokens(&tokens).map_err(|error| {
            error.span.map_or_else(
                || boxed_plain_diagnostic(format!("failed to balance {}: {error}", path.display())),
                |span| {
                    boxed_source_diagnostic(
                        format!("failed to balance {}: {error}", path.display()),
                        None,
                        &source,
                        span,
                    )
                },
            )
        })?;
        if let Some(attribute_span) = nwnrs_event_attribute_span(&stream) {
            invocation_span.get_or_insert(attribute_span);
        }
        let relative = path.strip_prefix(&source_root).map_err(|error| {
            boxed_plain_diagnostic(format!("failed to relativize {}: {error}", path.display()))
        })?;
        let include_path = relative.with_extension("");
        let include = include_path
            .to_str()
            .ok_or_else(|| {
                boxed_plain_diagnostic(format!(
                    "logical event source path must be valid UTF-8: {}",
                    path.display()
                ))
            })?
            .replace('\\', "/");
        let start = Span::new(source_id, 0, 0);
        let end = Span::new(source_id, source.len(), source.len());
        source_input.push(NwTokenTree::Token(Token::new(
            TokenKind::Identifier,
            start,
            "__nwnrs_source",
        )));
        source_input.push(NwTokenTree::Token(Token::new(
            TokenKind::String,
            start,
            include,
        )));
        source_input.push(NwTokenTree::Group(NwTokenGroup {
            delimiter: NwDelimiter::Brace,
            open_span: start,
            close_span: end,
            stream,
        }));
        source_files.insert(source_id.get(), source);
    }
    let Some(invocation_span) = invocation_span else {
        return Ok(Some(GeneratedEventDispatcher {
            name:         "_nwnrs_onload".to_string(),
            source:       GeneratedNwScriptSource::new(EMPTY_EVENT_DISPATCHER.as_bytes().to_vec()),
            include_root: source_root,
            plan:         empty_event_project_plan(),
        }));
    };
    if recovery.is_some() && recovery_token.is_none() {
        return Err(boxed_plain_diagnostic(
            "active event recovery source is outside the current package",
        ));
    }
    let mut macro_input = event_catalog_macro_input(invocation_span, recovery_token.as_ref());
    macro_input.extend(source_input);
    cancellation
        .check()
        .map_err(|error| boxed_plain_diagnostic(error.to_string()))?;
    let macro_registry = session
        .macro_registry_with_cancellation(cancellation)
        .map_err(plain_diagnostic)?;
    let (generated, plan) = run_event_dispatcher_macro(
        macro_registry.as_ref(),
        macro_input,
        invocation_span,
        &source_files,
        recovery_token.as_ref().map(|token| token.span),
        cancellation,
    )
    .map_err(|error| {
        error
            .span
            .and_then(|span| {
                source_files
                    .get(&span.source_id.get())
                    .map(|file| (file, span))
            })
            .map_or_else(
                || {
                    boxed_plain_diagnostic(format!(
                        "failed to execute nwnrs event project macro: {error}"
                    ))
                },
                |(file, span)| {
                    boxed_source_diagnostic(
                        format!("failed to execute nwnrs event project macro: {error}"),
                        None,
                        file,
                        span,
                    )
                },
            )
    })?;
    cancellation
        .check()
        .map_err(|error| boxed_plain_diagnostic(error.to_string()))?;
    Ok(Some(GeneratedEventDispatcher {
        name: "_nwnrs_onload".to_string(),
        source: GeneratedNwScriptSource::new(generated),
        include_root: source_root,
        plan,
    }))
}

fn event_catalog_macro_input(span: Span, recovery_token: Option<&Token>) -> NwTokenStream {
    let mut input = NwTokenStream::new();
    if let Some(recovery_token) = recovery_token {
        input.push(NwTokenTree::Token(Token::new(
            TokenKind::Identifier,
            span,
            "__nwnrs_editor_recovery",
        )));
        input.push(NwTokenTree::Token(recovery_token.clone()));
    }
    for event in nwnrs_runtime::EVENT_CATALOG {
        input.push(NwTokenTree::Token(Token::new(
            TokenKind::Identifier,
            span,
            "__nwnrs_event",
        )));
        for value in [event.subject, event.name, event.phase] {
            input.push(NwTokenTree::Token(Token::new(
                TokenKind::String,
                span,
                value,
            )));
        }
    }
    input
}

fn nwnrs_event_attribute_span(stream: &NwTokenStream) -> Option<Span> {
    stream.trees().windows(2).find_map(|trees| {
        let [NwTokenTree::Token(hash), NwTokenTree::Group(attribute)] = trees else {
            return None;
        };
        if hash.kind != TokenKind::Hash || !is_nwnrs_event_attribute(attribute) {
            return None;
        }
        Some(Span::new(
            hash.span.source_id,
            hash.span.start,
            attribute.span().end,
        ))
    })
}

fn run_event_dispatcher_macro(
    registry: &MacroRegistry,
    input: NwTokenStream,
    invocation_span: Span,
    source_files: &BTreeMap<u32, SourceFile>,
    recovery_span: Option<Span>,
    cancellation: &CancellationToken,
) -> Result<(Vec<u8>, EventProjectPlan), nwnrs_nwscript::MacroExpansionError> {
    let quoted = expand_registered_macro_with_cancellation(
        registry,
        "nwnrs::__build_event_dispatcher",
        input,
        invocation_span,
        MacroExpansionOptions::default(),
        cancellation,
    )?;
    decode_event_project_output(&quoted, source_files, recovery_span)
}

fn decode_event_project_output(
    output: &NwTokenStream,
    source_files: &BTreeMap<u32, SourceFile>,
    recovery_span: Option<Span>,
) -> Result<(Vec<u8>, EventProjectPlan), nwnrs_nwscript::MacroExpansionError> {
    let trees = output.trees();
    let [NwTokenTree::Token(marker), NwTokenTree::Group(project)] = trees else {
        return Err(nwnrs_nwscript::MacroExpansionError::without_span(
            "event project macro returned an invalid output envelope",
        ));
    };
    if marker.text != "__nwnrs_event_project" || project.delimiter != NwDelimiter::Brace {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            marker.span,
            "event project macro returned an unknown output envelope",
        ));
    }
    let sections = project.stream.trees();
    if sections.len() != 12 {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            project.span(),
            "event project macro output must contain exactly six sections",
        ));
    }
    let includes = event_output_section(sections, 0, "__nwnrs_includes")?;
    let helper = event_output_section(sections, 2, "__nwnrs_subscription_helper")?;
    let setup = event_output_section(sections, 4, "__nwnrs_event_setup")?;
    let handlers = event_output_section(sections, 6, "__nwnrs_ordered_handlers")?;
    let status = event_output_section(sections, 8, "__nwnrs_complete")?;
    let diagnostics = event_output_section(sections, 10, "__nwnrs_diagnostics")?;
    let [NwTokenTree::Token(complete)] = status.stream.trees() else {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            status.span(),
            "event project completion status must contain exactly one token",
        ));
    };
    let complete = match complete.text.as_str() {
        "TRUE" => true,
        "FALSE" => false,
        _ => {
            return Err(nwnrs_nwscript::MacroExpansionError::new(
                complete.span,
                "event project completion status must be TRUE or FALSE",
            ));
        }
    };

    let mut plan = EventProjectPlan {
        complete,
        diagnostics: event_output_diagnostics(source_files, diagnostics)?,
        ..EventProjectPlan::default()
    };
    let mut lane_indexes = BTreeMap::<(String, String), usize>::new();
    let mut seen_subscriptions = BTreeSet::new();
    let mut seen_includes = BTreeSet::new();
    let mut dispatch_source = Vec::new();

    let handler_trees = handlers.stream.trees();
    let (handler_records, remainder) = handler_trees.as_chunks::<2>();
    if !remainder.is_empty() {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            handlers.span(),
            "ordered event handler records are not marker-group pairs",
        ));
    }
    for pair in handler_records {
        let [
            NwTokenTree::Token(wrapper_marker),
            NwTokenTree::Group(wrapper),
        ] = pair
        else {
            return Err(nwnrs_nwscript::MacroExpansionError::new(
                pair.first()
                    .map_or_else(|| handlers.span(), NwTokenTree::span),
                "ordered event handler record is malformed",
            ));
        };
        if wrapper_marker.text != "__nwnrs_ordered_handler"
            || wrapper.delimiter != NwDelimiter::Brace
        {
            return Err(nwnrs_nwscript::MacroExpansionError::new(
                wrapper_marker.span,
                "ordered event handler record has an invalid envelope",
            ));
        }
        let record = wrapper.stream.trees();
        if record.len() != 15 {
            return Err(nwnrs_nwscript::MacroExpansionError::new(
                wrapper.span(),
                "ordered event handler record has an invalid field count",
            ));
        }
        let registration_marker = event_output_token(record, 0, "__nwnrs_registration")?;
        let subject = event_output_token_value(record, 1)?;
        let runtime_name = event_output_token_value(record, 2)?;
        let phase = event_output_token_value(record, 3)?;
        let source_subject = event_output_token_value(record, 4)?;
        let source_phase = event_output_token_value(record, 5)?;
        let handler = event_output_token_value(record, 6)?;
        let source_name = event_output_token_value(record, 7)?;
        let attribute_hash = event_output_token(record, 8, "#")?;
        let attribute = event_output_group(record, 9, NwDelimiter::Bracket)?;
        let parameters = event_output_group(record, 10, NwDelimiter::Parenthesis)?;
        let before_group = event_output_group(record, 11, NwDelimiter::Brace)?;
        let after_group = event_output_group(record, 12, NwDelimiter::Brace)?;
        let _dispatch_marker = event_output_token(record, 13, "__nwnrs_dispatch")?;
        let dispatch = event_output_group(record, 14, NwDelimiter::Brace)?;
        let subject_token = event_output_value_token(record, 4)?;
        let phase_token = event_output_value_token(record, 5)?;
        let handler_token = event_output_value_token(record, 6)?;
        if source_subject != subject || source_phase != phase {
            return Err(nwnrs_nwscript::MacroExpansionError::new(
                subject_token.span,
                "event project macro route metadata disagrees with its catalog route",
            ));
        }

        let attribute_range = event_source_range(
            source_files,
            Span::new(
                attribute_hash.span.source_id,
                attribute_hash.span.start,
                attribute.span().end,
            ),
        )?;
        let subject_range = event_source_range(source_files, subject_token.span)?;
        let phase_range = event_source_range(source_files, phase_token.span)?;
        let handler_range = event_source_range(source_files, handler_token.span)?;
        let declaration_range = event_source_range(
            source_files,
            Span::new(
                handler_token.span.source_id,
                handler_token.span.start,
                parameters.span().end,
            ),
        )?;
        let before = event_relations(source_files, before_group, recovery_span)?;
        let after = event_relations(source_files, after_group, recovery_span)?;
        let registration_index = plan.registrations.len();
        plan.registrations.push(EventRegistration {
            subject: subject.clone(),
            runtime_name,
            phase: phase.clone(),
            subject_range,
            phase_range,
            handler,
            attribute_range,
            handler_range,
            declaration_range,
            before,
            after,
        });

        let route = (subject.clone(), phase.clone());
        if seen_subscriptions.insert(route.clone()) {
            plan.subscriptions.push(route.clone());
        }
        let lane_index = *lane_indexes.entry(route.clone()).or_insert_with(|| {
            let index = plan.lanes.len();
            plan.lanes.push(EventLanePlan {
                subject:       route.0.clone(),
                phase:         route.1.clone(),
                registrations: Vec::new(),
            });
            index
        });
        let lane = plan.lanes.get_mut(lane_index).ok_or_else(|| {
            nwnrs_nwscript::MacroExpansionError::new(
                registration_marker.span,
                "event project macro produced an invalid lane index",
            )
        })?;
        lane.registrations.push(registration_index);
        if seen_includes.insert(source_name.clone()) {
            plan.includes.push(source_name);
        }
        dispatch_source.extend(render_nwscript_tokens_bytes(&dispatch.stream));
        dispatch_source.push(b'\n');
        let _ = registration_marker;
    }

    let mut generated = b"/// Generated by nwpkg. Do not edit.\n".to_vec();
    generated.extend(render_nwscript_tokens_bytes(&includes.stream));
    generated.push(b'\n');
    generated.extend(render_nwscript_tokens_bytes(&helper.stream));
    generated.extend_from_slice(b"\nvoid main()\n{\n");
    generated.extend(render_nwscript_tokens_bytes(&setup.stream));
    generated.push(b'\n');
    generated.extend(dispatch_source);
    generated.extend_from_slice(b"}\n");
    Ok((generated, plan))
}

fn event_output_diagnostics(
    source_files: &BTreeMap<u32, SourceFile>,
    group: &NwTokenGroup,
) -> Result<Vec<CompilerDiagnostic>, nwnrs_nwscript::MacroExpansionError> {
    let (records, remainder) = group.stream.trees().as_chunks::<3>();
    if !remainder.is_empty() {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            group.span(),
            "event project diagnostic records are malformed",
        ));
    }
    records
        .iter()
        .map(|record| {
            let _marker = event_output_token(record, 0, "__nwnrs_diagnostic")?;
            let message = event_output_token_value(record, 1)?;
            let token = event_output_value_token(record, 2)?;
            let source = source_files
                .get(&token.span.source_id.get())
                .ok_or_else(|| {
                    nwnrs_nwscript::MacroExpansionError::new(
                        token.span,
                        "event project diagnostic references an unknown source",
                    )
                })?;
            Ok(source_diagnostic(message, None, source, token.span))
        })
        .collect()
}

fn event_output_section<'a>(
    trees: &'a [NwTokenTree],
    index: usize,
    expected: &str,
) -> Result<&'a NwTokenGroup, nwnrs_nwscript::MacroExpansionError> {
    let marker = event_output_token(trees, index, expected)?;
    let group = event_output_group(trees, index + 1, NwDelimiter::Brace)?;
    let _ = marker;
    Ok(group)
}

fn event_output_token<'a>(
    trees: &'a [NwTokenTree],
    index: usize,
    expected: &str,
) -> Result<&'a Token, nwnrs_nwscript::MacroExpansionError> {
    let Some(tree) = trees.get(index) else {
        return Err(nwnrs_nwscript::MacroExpansionError::without_span(
            "event project macro output ended unexpectedly",
        ));
    };
    let NwTokenTree::Token(token) = tree else {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            tree.span(),
            format!("event project macro expected marker `{expected}`"),
        ));
    };
    if token.text != expected {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            token.span,
            format!("event project macro expected marker `{expected}`"),
        ));
    }
    Ok(token)
}

fn event_output_token_value(
    trees: &[NwTokenTree],
    index: usize,
) -> Result<String, nwnrs_nwscript::MacroExpansionError> {
    event_output_value_token(trees, index).map(|token| token.text.clone())
}

fn event_output_value_token(
    trees: &[NwTokenTree],
    index: usize,
) -> Result<&Token, nwnrs_nwscript::MacroExpansionError> {
    let Some(tree) = trees.get(index) else {
        return Err(nwnrs_nwscript::MacroExpansionError::without_span(
            "event project macro output ended unexpectedly",
        ));
    };
    let NwTokenTree::Token(token) = tree else {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            tree.span(),
            "event project macro expected a token field",
        ));
    };
    Ok(token)
}

fn event_output_group(
    trees: &[NwTokenTree],
    index: usize,
    delimiter: NwDelimiter,
) -> Result<&NwTokenGroup, nwnrs_nwscript::MacroExpansionError> {
    let Some(tree) = trees.get(index) else {
        return Err(nwnrs_nwscript::MacroExpansionError::without_span(
            "event project macro output ended unexpectedly",
        ));
    };
    let NwTokenTree::Group(group) = tree else {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            tree.span(),
            "event project macro expected a grouped field",
        ));
    };
    if group.delimiter != delimiter {
        return Err(nwnrs_nwscript::MacroExpansionError::new(
            group.span(),
            "event project macro field uses the wrong delimiter",
        ));
    }
    Ok(group)
}

fn event_source_range(
    source_files: &BTreeMap<u32, SourceFile>,
    span: Span,
) -> Result<EventSourceRange, nwnrs_nwscript::MacroExpansionError> {
    let source = source_files.get(&span.source_id.get()).ok_or_else(|| {
        nwnrs_nwscript::MacroExpansionError::new(
            span,
            "event project macro record references an unknown source",
        )
    })?;
    let start = source.location(span.start).ok_or_else(|| {
        nwnrs_nwscript::MacroExpansionError::new(
            span,
            "event project macro range starts outside its source",
        )
    })?;
    let end = source.location(span.end.min(source.len())).ok_or_else(|| {
        nwnrs_nwscript::MacroExpansionError::new(
            span,
            "event project macro range ends outside its source",
        )
    })?;
    Ok(EventSourceRange {
        path:         PathBuf::from(&source.name),
        start_offset: span.start,
        end_offset:   span.end,
        start_line:   start.line,
        start_column: start.column,
        end_line:     end.line,
        end_column:   end.column,
    })
}

fn event_relations(
    source_files: &BTreeMap<u32, SourceFile>,
    group: &NwTokenGroup,
    recovery_span: Option<Span>,
) -> Result<Vec<EventRelation>, nwnrs_nwscript::MacroExpansionError> {
    group
        .stream
        .trees()
        .iter()
        .map(|tree| {
            let NwTokenTree::Token(token) = tree else {
                return Err(nwnrs_nwscript::MacroExpansionError::new(
                    tree.span(),
                    "event relation metadata must contain identifiers",
                ));
            };
            if recovery_span.is_some_and(|span| token.span == span) {
                Ok(None)
            } else {
                Ok(Some(EventRelation {
                    target: token.text.clone(),
                    range:  event_source_range(source_files, token.span)?,
                }))
            }
        })
        .filter_map(|relation| match relation {
            Ok(Some(relation)) => Some(Ok(relation)),
            Ok(None) => None,
            Err(error) => Some(Err(error)),
        })
        .collect()
}

#[derive(Debug, Clone)]
struct EventEditToken {
    text:  String,
    start: usize,
    end:   usize,
}

fn event_completion_context(
    source: &[u8],
    cursor_offset: usize,
    compiler_tokens: &[Token],
) -> Option<EventCompletionContext> {
    let cursor_offset = cursor_offset.min(source.len());
    let attribute_start = compiler_tokens
        .windows(2)
        .filter_map(|pair| {
            let [hash, bracket] = pair else {
                return None;
            };
            (hash.kind == TokenKind::Hash
                && bracket.kind == TokenKind::LeftSquareBracket
                && hash.span.start <= cursor_offset
                && !compiler_tokens.iter().any(|token| {
                    token.kind == TokenKind::RightSquareBracket
                        && token.span.start > bracket.span.start
                        && token.span.end <= cursor_offset
                }))
            .then_some(hash.span.start)
        })
        .next_back()?;
    let tokens = event_edit_tokens(compiler_tokens, attribute_start, cursor_offset);
    let [hash, bracket, namespace, first_colon, second_colon, ..] = tokens.as_slice() else {
        return None;
    };
    if hash.text != "#"
        || bracket.text != "["
        || namespace.text != "nwnrs"
        || first_colon.text != ":"
        || second_colon.text != ":"
    {
        return None;
    }
    let mut position = 5;
    let (construct, construct_start, construct_end) =
        event_active_identifier(&tokens, position, cursor_offset, source);
    if tokens
        .get(position)
        .is_none_or(|token| token.text != "event")
        || !event_double_colon(&tokens, position + 1)
    {
        return Some(event_context(
            EventCompletionKind::Construct,
            construct,
            construct_start,
            construct_end,
            attribute_start,
            None,
            None,
            None,
        ));
    }
    position += 3;
    let (subject, subject_start, subject_end) =
        event_active_identifier(&tokens, position, cursor_offset, source);
    let Some(subject_token) = tokens.get(position) else {
        return Some(event_context(
            EventCompletionKind::Subject,
            subject,
            subject_start,
            subject_end,
            attribute_start,
            None,
            None,
            None,
        ));
    };
    if !event_double_colon(&tokens, position + 1) {
        return Some(event_context(
            EventCompletionKind::Subject,
            subject,
            subject_start,
            subject_end,
            attribute_start,
            None,
            None,
            None,
        ));
    }
    let subject = subject_token.text.clone();
    position += 3;
    let (phase, phase_start, phase_end) =
        event_active_identifier(&tokens, position, cursor_offset, source);
    let Some(phase_token) = tokens.get(position) else {
        return Some(event_context(
            EventCompletionKind::Phase,
            phase,
            phase_start,
            phase_end,
            attribute_start,
            Some(subject),
            None,
            None,
        ));
    };
    if tokens
        .get(position + 1)
        .is_none_or(|token| token.text != "(")
    {
        return Some(event_context(
            EventCompletionKind::Phase,
            phase,
            phase_start,
            phase_end,
            attribute_start,
            Some(subject),
            None,
            None,
        ));
    }
    let phase = phase_token.text.clone();
    position += 2;

    loop {
        let (modifier, modifier_start, modifier_end) =
            event_active_identifier(&tokens, position, cursor_offset, source);
        let Some(modifier_token) = tokens.get(position) else {
            return Some(event_context(
                EventCompletionKind::Modifier,
                modifier,
                modifier_start,
                modifier_end,
                attribute_start,
                Some(subject),
                Some(phase),
                None,
            ));
        };
        if !matches!(modifier_token.text.as_str(), "before" | "after")
            || tokens
                .get(position + 1)
                .is_none_or(|token| token.text != "(")
        {
            return Some(event_context(
                EventCompletionKind::Modifier,
                modifier,
                modifier_start,
                modifier_end,
                attribute_start,
                Some(subject),
                Some(phase),
                None,
            ));
        }
        let modifier = modifier_token.text.clone();
        position += 2;
        loop {
            let (target, target_start, target_end) =
                event_active_identifier(&tokens, position, cursor_offset, source);
            let Some(_target_token) = tokens.get(position) else {
                return Some(event_context(
                    EventCompletionKind::Target,
                    target,
                    target_start,
                    target_end,
                    attribute_start,
                    Some(subject),
                    Some(phase),
                    Some(modifier),
                ));
            };
            if tokens.get(position + 1).is_none() {
                return Some(event_context(
                    EventCompletionKind::Target,
                    target,
                    target_start,
                    target_end,
                    attribute_start,
                    Some(subject),
                    Some(phase),
                    Some(modifier),
                ));
            }
            position += 1;
            match tokens.get(position).map(|token| token.text.as_str()) {
                Some(",") => position += 1,
                Some(")") => {
                    position += 1;
                    break;
                }
                None => {
                    return Some(event_context(
                        EventCompletionKind::Target,
                        String::new(),
                        cursor_offset,
                        cursor_offset,
                        attribute_start,
                        Some(subject),
                        Some(phase),
                        Some(modifier),
                    ));
                }
                _ => return None,
            }
        }
        match tokens.get(position).map(|token| token.text.as_str()) {
            Some(",") => position += 1,
            Some(")") | Some("]") | None => return None,
            _ => return None,
        }
    }
}

fn event_context(
    kind: EventCompletionKind,
    prefix: String,
    replacement_start: usize,
    replacement_end: usize,
    attribute_start: usize,
    subject: Option<String>,
    phase: Option<String>,
    modifier: Option<String>,
) -> EventCompletionContext {
    EventCompletionContext {
        kind,
        prefix,
        replacement_start,
        replacement_end,
        subject,
        phase,
        modifier,
        attribute_start,
    }
}

fn event_active_identifier(
    tokens: &[EventEditToken],
    position: usize,
    cursor_offset: usize,
    source: &[u8],
) -> (String, usize, usize) {
    tokens.get(position).map_or_else(
        || (String::new(), cursor_offset, cursor_offset),
        |token| {
            if token
                .text
                .as_bytes()
                .first()
                .is_some_and(|byte| byte.is_ascii_alphabetic() || *byte == b'_')
                && tokens.get(position + 1).is_none()
            {
                let mut end = token.end;
                while source
                    .get(end)
                    .is_some_and(|byte| byte.is_ascii_alphanumeric() || *byte == b'_')
                {
                    end += 1;
                }
                let prefix_end = cursor_offset.min(token.end);
                let prefix = source
                    .get(token.start..prefix_end)
                    .filter(|bytes| bytes.is_ascii())
                    .map_or_else(String::new, |bytes| {
                        bytes.iter().map(|byte| char::from(*byte)).collect()
                    });
                (prefix, token.start, end)
            } else {
                (String::new(), cursor_offset, cursor_offset)
            }
        },
    )
}

fn event_double_colon(tokens: &[EventEditToken], position: usize) -> bool {
    tokens.get(position).is_some_and(|token| token.text == ":")
        && tokens
            .get(position + 1)
            .is_some_and(|token| token.text == ":")
}

fn event_edit_tokens(compiler_tokens: &[Token], start: usize, end: usize) -> Vec<EventEditToken> {
    compiler_tokens
        .iter()
        .filter(|token| token.kind != TokenKind::Eof)
        .filter(|token| token.span.start >= start && token.span.start < end)
        .map(|token| EventEditToken {
            text:  token.text.clone(),
            start: token.span.start,
            end:   token.span.end,
        })
        .collect()
}

fn recover_active_event_target_tokens(
    compiler_tokens: &[Token],
    context: &EventCompletionContext,
    source_id: SourceId,
) -> Option<(Vec<Token>, Token)> {
    if context.kind != EventCompletionKind::Target
        || context.replacement_start > context.replacement_end
    {
        return None;
    }
    let injected_span = Span::new(
        source_id,
        context.replacement_start,
        context.replacement_end,
    );
    let injected = Token::new(TokenKind::Identifier, injected_span, "__nwnrs_incomplete");
    let mut recovered = Vec::with_capacity(compiler_tokens.len().saturating_add(4));
    let mut inserted = false;
    for token in compiler_tokens
        .iter()
        .filter(|token| token.kind != TokenKind::Eof)
    {
        let overlaps = token.span.start < context.replacement_end
            && token.span.end > context.replacement_start;
        if !inserted && (overlaps || token.span.start >= context.replacement_start) {
            recovered.push(injected.clone());
            inserted = true;
        }
        if !overlaps {
            recovered.push(token.clone());
        }
    }
    if !inserted {
        recovered.push(injected.clone());
    }

    let attribute = recovered.iter().position(|token| {
        token.kind == TokenKind::Hash && token.span.start == context.attribute_start
    })?;
    let closing = recovered
        .iter()
        .enumerate()
        .skip(attribute + 1)
        .find(|(_index, token)| token.kind == TokenKind::RightSquareBracket)
        .map(|(index, _token)| index);
    let boundary = closing.unwrap_or_else(|| {
        recovered
            .iter()
            .enumerate()
            .skip(attribute + 2)
            .find(|(_index, token)| {
                token.span.start >= context.replacement_end
                    && matches!(token.kind, TokenKind::Hash | TokenKind::Keyword(_))
            })
            .map_or(recovered.len(), |(index, _token)| index)
    });
    let mut depth = 0_isize;
    for token in recovered.get(attribute..boundary).unwrap_or_default() {
        match token.kind {
            TokenKind::LeftParen => depth += 1,
            TokenKind::RightParen => depth -= 1,
            _ => {}
        }
    }
    let synthetic_span = Span::new(source_id, context.replacement_end, context.replacement_end);
    let missing = usize::try_from(depth.max(0)).ok()?;
    for _ in 0..missing {
        recovered.insert(
            boundary,
            Token::new(TokenKind::RightParen, synthetic_span, ")"),
        );
    }
    if closing.is_none() {
        recovered.insert(
            boundary.saturating_add(missing),
            Token::new(TokenKind::RightSquareBracket, synthetic_span, "]"),
        );
    }
    recovered.push(Token::new(TokenKind::Eof, synthetic_span, ""));
    Some((recovered, injected))
}

fn list_event_lane_handlers(
    plan: &EventProjectPlan,
    context: &EventCompletionContext,
) -> Vec<EventLaneCandidate> {
    let (Some(subject), Some(phase), Some(modifier)) = (
        context.subject.as_deref(),
        context.phase.as_deref(),
        context.modifier.as_deref(),
    ) else {
        return Vec::new();
    };
    let Some(current) = plan.registrations.iter().find(|registration| {
        registration.subject == subject
            && registration.phase == phase
            && context.attribute_start
                >= registration.attribute_range.start_offset.saturating_sub(1)
            && context.attribute_start <= registration.attribute_range.end_offset
    }) else {
        return Vec::new();
    };
    let Some(lane) = plan
        .lanes
        .iter()
        .find(|lane| lane.subject == subject && lane.phase == phase)
    else {
        return Vec::new();
    };
    let existing = current
        .before
        .iter()
        .chain(&current.after)
        .map(|relation| relation.target.as_str())
        .collect::<BTreeSet<_>>();
    let mut edges = BTreeMap::<&str, BTreeSet<&str>>::new();
    for registration_index in &lane.registrations {
        let Some(registration) = plan.registrations.get(*registration_index) else {
            continue;
        };
        for relation in &registration.before {
            edges
                .entry(registration.handler.as_str())
                .or_default()
                .insert(relation.target.as_str());
        }
        for relation in &registration.after {
            edges
                .entry(relation.target.as_str())
                .or_default()
                .insert(registration.handler.as_str());
        }
    }
    lane.registrations
        .iter()
        .enumerate()
        .filter_map(|(sort_order, registration_index)| {
            let registration = plan.registrations.get(*registration_index)?;
            if registration.handler == current.handler
                || existing.contains(registration.handler.as_str())
            {
                return None;
            }
            let (before, after) = if modifier == "before" {
                (current.handler.as_str(), registration.handler.as_str())
            } else {
                (registration.handler.as_str(), current.handler.as_str())
            };
            if event_graph_reaches(&edges, after, before) {
                return None;
            }
            Some(EventLaneCandidate {
                handler: registration.handler.clone(),
                definition: registration.handler_range.clone(),
                sort_order,
            })
        })
        .collect()
}

fn event_graph_reaches(edges: &BTreeMap<&str, BTreeSet<&str>>, start: &str, target: &str) -> bool {
    let mut pending = vec![start];
    let mut visited = BTreeSet::new();
    while let Some(node) = pending.pop() {
        if node == target {
            return true;
        }
        if visited.insert(node)
            && let Some(children) = edges.get(node)
        {
            pending.extend(children.iter().copied());
        }
    }
    false
}

fn plain_diagnostic(message: impl Into<String>) -> CompilerDiagnostic {
    CompilerDiagnostic {
        code:         None,
        message:      message.into(),
        file:         None,
        source:       None,
        start_line:   None,
        start_column: None,
        end_line:     None,
        end_column:   None,
        start_offset: None,
        end_offset:   None,
        source_bytes: None,
    }
}

fn boxed_plain_diagnostic(message: impl Into<String>) -> Box<CompilerDiagnostic> {
    Box::new(plain_diagnostic(message))
}

fn source_diagnostic(
    message: impl Into<String>,
    code: Option<i32>,
    file: &SourceFile,
    span: Span,
) -> CompilerDiagnostic {
    let start = file.location(span.start);
    let end = file.location(span.end.min(file.len()));
    CompilerDiagnostic {
        code,
        message: message.into(),
        file: Some(file.name.clone()),
        source: Path::new(&file.name)
            .is_absolute()
            .then(|| nwnrs_nwscript::ScriptSourceOrigin::Physical(PathBuf::from(&file.name))),
        start_line: start.map(|location| location.line),
        start_column: start.map(|location| location.column),
        end_line: end.map(|location| location.line),
        end_column: end.map(|location| location.column),
        start_offset: Some(span.start),
        end_offset: Some(span.end.min(file.len())),
        source_bytes: Some(file.contents.clone()),
    }
}

fn boxed_source_diagnostic(
    message: impl Into<String>,
    code: Option<i32>,
    file: &SourceFile,
    span: Span,
) -> Box<CompilerDiagnostic> {
    Box::new(source_diagnostic(message, code, file, span))
}

