    #[test]
    fn rejects_invalid_relationship_graphs_precisely() -> Result<(), String> {
        let cases = [
            (
                "empty-relationships",
                "#[nwnrs::event::object_use::before()]\nvoid Handle(json event) {}\n",
                "relationship list must not be empty",
            ),
            (
                "repeated-clause",
                "#[nwnrs::event::object_use::before(before(A), before(B))]\nvoid Handle(json \
                 event) {}\n",
                "at most one before clause",
            ),
            (
                "duplicate-target",
                "#[nwnrs::event::object_use::before(before(A, A))]\nvoid Handle(json event) {}\n",
                "duplicate target in event before clause",
            ),
            (
                "self-relation",
                "#[nwnrs::event::object_use::before(before(Handle))]\nvoid Handle(json event) {}\n",
                "cannot be ordered relative to itself",
            ),
            (
                "contradictory-clause",
                "#[nwnrs::event::object_use::before(before(A), after(A))]\nvoid Handle(json \
                 event) {}\n",
                "contradictory before and after relationship",
            ),
            (
                "missing-target",
                "#[nwnrs::event::object_use::before(before(Missing))]\nvoid Handle(json event) \
                 {}\n",
                "relationship target is not registered",
            ),
            (
                "cross-lane-target",
                "#[nwnrs::event::object_use::before(before(Other))]\nvoid Handle(json event) \
                 {}\n#[nwnrs::event::object_use::after]\nvoid Other(json event) {}\n",
                "registered only in another subject or phase",
            ),
            (
                "unsupported-phase",
                "#[nwnrs::event::module_load::after]\nvoid Handle(json event) {}\n",
                "unsupported phase for nwnrs event subject",
            ),
            (
                "duplicate-lane-registration",
                "#[nwnrs::event::object_use::before]\n#[nwnrs::event::object_use::before]\nvoid \
                 Handle(json event) {}\n",
                "registered more than once in the same event lane",
            ),
            (
                "unknown-modifier",
                "#[nwnrs::event::object_use::before(priority(A))]\nvoid Handle(json event) {}\n",
                "unknown event relationship modifier",
            ),
        ];
        for (name, source, expected) in cases {
            let root = event_test_root(name)?;
            fs::write(root.join("events.nss"), source).map_err(|error| error.to_string())?;
            let error = generate_event_dispatcher(&root)
                .expect_err("invalid relationship graph must be rejected");
            assert!(
                error.contains(expected),
                "{name} produced `{error}` instead of `{expected}`"
            );
            fs::remove_dir_all(root).map_err(|error| error.to_string())?;
        }
        Ok(())
    }

